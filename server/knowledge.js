// 시스템 프롬프트에 넣을 지식집 본문
export function knowledgePrompt() {
  const list = (patterns) =>
    patterns.map((p) => `- [${p.id}] ${p.name}\n${p.signs.map((s) => `    - ${s}`).join('\n')}`).join('\n')
  return `
[판별 지식집: 출시 전 조사한 실제 사례]
가짜 수법:
${list(FAKE_PATTERNS)}

진짜 경고와 알림:
${list(REAL_PATTERNS)}

핵심 구별 규칙:
- 진짜 경고는 "앱 지우기, 설치하지 않기, 설정에서 확인하기"처럼 안전한 쪽을 권한다.
- 가짜는 "앱 설치하기, 전화하기, 개인정보 입력하기, 결제하기"를 권한다.
- 무섭게 생겼다고 가짜는 아니다 (예: Play 프로텍트). 권하는 행동을 보고 판단한다.
- 정상 앱(PDF 뷰어, 게임 등)이 무료 이용 대가로 띄우는 "광고 로딩 중" 같은 평범한 광고는 가짜 경고가 아니다. 아무것도 요구하지 않으면 verdict 를 "ad" 로 하고, headline 에 "평범한 광고예요. 위험하지는 않아요"처럼 쓴다. 이 화면을 이유로 앱을 지우라고 하지 않는다.
- 진짜 "경고"(Play 프로텍트, 설치 차단 창)는 화면은 진짜지만 위험을 알리는 것이다. headline 에 "안전하다"고 쓰지 말고 "진짜 경고예요. 경고대로 앱을 지우세요"처럼 경고를 따르라고 쓴다.

진짜인지 확인하는 법 (verify_tip 에는 이 중 화면에 가장 알맞은 것을 쉬운 말로 한 문장):
${VERIFY_TIPS.map((t) => `- ${t}`).join('\n')}`
}
